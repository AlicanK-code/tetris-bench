"""Tetromino shapes and their rotation states.

Coordinates are ``(row, column)`` offsets inside the piece's own bounding box,
with **row 0 at the top**. Shapes are normalised so the smallest row and the
smallest column are both 0. That normalisation is what makes column enumeration
in :mod:`tetris_bench.engine.placements` simple: a shape of width ``w`` can sit
at columns ``0 .. board_width - w``.

Rotation states are generated by rotating the spawn shape 90 degrees clockwise
and discarding duplicates, so a piece has 1, 2 or 4 states rather than always 4:
the ``O`` piece looks identical in every orientation, and ``I``, ``S`` and ``Z``
repeat after two turns.

We can get away with that because this benchmark is placement-based: a piece is
rotated in free space and then dropped straight down, so it is never rotated
against an obstruction and we need no SRS wall-kick tables -- only the set of
distinct shapes. The consequence is that a rotation index here is an index into
this module's ``rotations`` tuple and does **not** always match the usual SRS
numbering. That is deliberate, and it keeps the placement list free of
duplicates that would otherwise be offered to a model as distinct choices.
"""

from __future__ import annotations

from dataclasses import dataclass

Cell = tuple[int, int]
"""A single ``(row, column)`` coordinate."""

Shape = tuple[Cell, ...]
"""The four cells of a tetromino in one orientation, normalised and sorted."""

PIECE_KINDS: tuple[str, ...] = ("I", "O", "T", "S", "Z", "J", "L")
"""The seven tetrominoes, in the order used to fill a 7-bag."""

# Spawn orientations, written out as the familiar SRS shapes so they are easy to
# eyeball against a diagram. Row 0 is the top row of each sketch.
SPAWN_SHAPES: dict[str, Shape] = {
    # XXXX
    "I": ((0, 0), (0, 1), (0, 2), (0, 3)),
    # XX
    # XX
    "O": ((0, 0), (0, 1), (1, 0), (1, 1)),
    # .X.
    # XXX
    "T": ((0, 1), (1, 0), (1, 1), (1, 2)),
    # .XX
    # XX.
    "S": ((0, 1), (0, 2), (1, 0), (1, 1)),
    # XX.
    # .XX
    "Z": ((0, 0), (0, 1), (1, 1), (1, 2)),
    # X..
    # XXX
    "J": ((0, 0), (1, 0), (1, 1), (1, 2)),
    # ..X
    # XXX
    "L": ((0, 2), (1, 0), (1, 1), (1, 2)),
}


def normalise(shape: Shape) -> Shape:
    """Shift a shape so its smallest row and column are 0, and sort its cells.

    Sorting matters: it makes two shapes that occupy the same cells compare
    equal, which is how duplicate rotations are detected.
    """
    min_row = min(r for r, _ in shape)
    min_col = min(c for _, c in shape)
    return tuple(sorted((r - min_row, c - min_col) for r, c in shape))


def rotate_cw(shape: Shape) -> Shape:
    """Rotate a shape 90 degrees clockwise.

    In a bounding box of height ``h``, a clockwise turn sends ``(r, c)`` to
    ``(c, h - 1 - r)``: the old column becomes the new row, and the old row is
    mirrored to become the new column.
    """
    height = max(r for r, _ in shape) + 1
    return normalise(tuple((c, height - 1 - r) for r, c in shape))


def _distinct_rotations(spawn: Shape) -> tuple[Shape, ...]:
    """Return the unique orientations of a shape, in clockwise order."""
    rotations: list[Shape] = []
    current = normalise(spawn)
    for _ in range(4):
        if current not in rotations:
            rotations.append(current)
        current = rotate_cw(current)
    return tuple(rotations)


@dataclass(frozen=True)
class Piece:
    """A tetromino and all of its distinct orientations."""

    kind: str
    rotations: tuple[Shape, ...]

    def shape(self, rotation: int) -> Shape:
        """The cells of this piece in the given rotation state."""
        return self.rotations[rotation]

    def width(self, rotation: int) -> int:
        """How many columns the piece spans in the given rotation state."""
        return max(c for _, c in self.rotations[rotation]) + 1

    def height(self, rotation: int) -> int:
        """How many rows the piece spans in the given rotation state."""
        return max(r for r, _ in self.rotations[rotation]) + 1

    @property
    def rotation_count(self) -> int:
        """The number of distinct orientations (1 for O, 2 for I/S/Z, else 4)."""
        return len(self.rotations)


PIECES: dict[str, Piece] = {
    kind: Piece(kind=kind, rotations=_distinct_rotations(shape))
    for kind, shape in SPAWN_SHAPES.items()
}
"""Every tetromino, keyed by its letter."""
